def calculate_costs(candidate):
    part = copy.deepcopy(candidate)
    price = Decimal(str(part["price_gbp"]))
    penny = Decimal("0.01")
    part["cost_per_drawer_gbp"] = float(
        (price / Decimal(str(part["number_of_drawers"]))).quantize(
            penny, rounding=ROUND_HALF_UP
        )
    )
    weight = part.get("weight_kg")
    part["cost_per_kg_gbp"] = None
    part["cost_per_kg_basis"] = part["weight_basis"]
    if weight is not None and weight > 0:
        part["cost_per_kg_gbp"] = float(
            (price / Decimal(str(weight))).quantize(penny, rounding=ROUND_HALF_UP)
        )
    return part


